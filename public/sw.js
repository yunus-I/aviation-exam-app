// ============================================================
// EAU Mini App - Service Worker Purger
// Actively unregisters itself and purges stale caches to prevent
// Android/iOS WebView freezes and white-screen issues.
// ============================================================

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(keys.map((key) => caches.delete(key)));
    }).then(() => {
      return self.registration.unregister();
    })
  );
  self.clients.claim();
});
